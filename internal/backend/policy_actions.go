// IsKnownS3PolicyAction reports whether action (e.g. "s3:GetObject") is an
// IAM action of the s3 namespace. Action names are case-insensitive.
func IsKnownS3PolicyAction(action string) bool {
	_, ok := s3PolicyActions[strings.ToLower(action)]
	return ok
}
